static HRESULT compile(const char *src, size_t n, const char *name, const char *entry, const char *target,
                       ID3DBlob **out)
{
    ID3DBlob *err = NULL;
    HRESULT hr = D3DCompile(src, n, name, NULL, NULL, entry, target, D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, out, &err);

    if (FAILED(hr))
        fprintf(stderr, "[AA] %s %s not compiled (0x%08lX)%s%.600s\n", name, entry, (unsigned long)hr,
                err ? ": " : "", err ? (const char *)ID3D10Blob_GetBufferPointer(err) : "");
    RELEASE(ID3D10Blob, err);
    return hr;
}

static HRESULT make_vs(const char *src, size_t n, const char *name, const char *entry, ID3D11VertexShader **vs)
{
    ID3DBlob *b = NULL;
    HRESULT hr = compile(src, n, name, entry, "vs_4_0", &b);

    if (SUCCEEDED(hr))
        hr = ID3D11Device_CreateVertexShader(d3d8_GetD3D11Device(), ID3D10Blob_GetBufferPointer(b),
                                             ID3D10Blob_GetBufferSize(b), NULL, vs);
    RELEASE(ID3D10Blob, b);
    return hr;
}

static HRESULT make_ps(const char *src, size_t n, const char *name, const char *entry, ID3D11PixelShader **ps)
{
    ID3DBlob *b = NULL;
    HRESULT hr = compile(src, n, name, entry, "ps_4_0", &b);

    if (SUCCEEDED(hr))
        hr = ID3D11Device_CreatePixelShader(d3d8_GetD3D11Device(), ID3D10Blob_GetBufferPointer(b),
                                            ID3D10Blob_GetBufferSize(b), NULL, ps);
    RELEASE(ID3D10Blob, b);
    return hr;
}

/* The full-screen triangle, the copy, FXAA, the samplers and the constants. */
static int fx_init(void)
{
    ID3D11Device *d = d3d8_GetD3D11Device();
    D3D11_SAMPLER_DESC sd;
    D3D11_BUFFER_DESC bd;
    HRESULT hr;

    if (g_aa.fx)
        return g_aa.fx > 0 ? 0 : -1;
    g_aa.fx = -1;
    hr = make_vs(g_fx_hlsl, sizeof(g_fx_hlsl) - 1, "twoc_fx", "vs", &g_aa.vs);
    if (SUCCEEDED(hr))
        hr = make_ps(g_fx_hlsl, sizeof(g_fx_hlsl) - 1, "twoc_fx", "copy_ps", &g_aa.copy_ps);
    if (SUCCEEDED(hr))
        hr = make_ps(g_fx_hlsl, sizeof(g_fx_hlsl) - 1, "twoc_fx", "fxaa_ps", &g_aa.fxaa_ps);
    if (SUCCEEDED(hr)) {
        memset(&sd, 0, sizeof(sd));
        sd.Filter = D3D11_FILTER_MIN_MAG_LINEAR_MIP_POINT;
        sd.AddressU = sd.AddressV = sd.AddressW = D3D11_TEXTURE_ADDRESS_CLAMP;
        sd.ComparisonFunc = D3D11_COMPARISON_NEVER;
        sd.MaxLOD = D3D11_FLOAT32_MAX;
        hr = ID3D11Device_CreateSamplerState(d, &sd, &g_aa.linear);
        sd.Filter = D3D11_FILTER_MIN_MAG_MIP_POINT;
        if (SUCCEEDED(hr))
            hr = ID3D11Device_CreateSamplerState(d, &sd, &g_aa.point);
    }
    if (SUCCEEDED(hr)) {
        memset(&bd, 0, sizeof(bd));
        bd.ByteWidth = 16;
        bd.Usage = D3D11_USAGE_DEFAULT;
        bd.BindFlags = D3D11_BIND_CONSTANT_BUFFER;
        hr = ID3D11Device_CreateBuffer(d, &bd, NULL, &g_aa.cb);
    }
    if (FAILED(hr)) {
        fprintf(stderr, "[AA] FXAA and the MSAA copy not available (0x%08lX)\n", (unsigned long)hr);
        return -1;
    }
    g_aa.fx = 1;
    return 0;
}

static HRESULT make_lut(unsigned w, unsigned h, DXGI_FORMAT fmt, const void *bits, unsigned pitch,
                        ID3D11Texture2D **tex, ID3D11ShaderResourceView **srv)
{
    D3D11_TEXTURE2D_DESC td;
    D3D11_SUBRESOURCE_DATA sd;
    HRESULT hr;

    memset(&td, 0, sizeof(td));
    td.Width = w;
    td.Height = h;
    td.MipLevels = 1;
    td.ArraySize = 1;
    td.Format = fmt;
    td.SampleDesc.Count = 1;
    td.Usage = D3D11_USAGE_IMMUTABLE;
    td.BindFlags = D3D11_BIND_SHADER_RESOURCE;
    sd.pSysMem = bits;
    sd.SysMemPitch = pitch;
    sd.SysMemSlicePitch = 0;
    hr = ID3D11Device_CreateTexture2D(d3d8_GetD3D11Device(), &td, &sd, tex);
    if (SUCCEEDED(hr))
        hr = ID3D11Device_CreateShaderResourceView(d3d8_GetD3D11Device(), (ID3D11Resource *)*tex, NULL, srv);
    return hr;
}

/* SMAA's shaders (compiled here, once) and its two lookup textures. */
static int smaa_init(void)
{
    LARGE_INTEGER f, t0, t1;
    size_t n_pre = sizeof(g_smaa_pre) - 1, n_src = sizeof(g_smaa_hlsl) - 1, n_post = sizeof(g_smaa_post) - 1;
    char *src;
    HRESULT hr;

    if (g_aa.smaa)
        return g_aa.smaa > 0 ? 0 : -1;
    g_aa.smaa = -1;
    if (fx_init() != 0)
        return -1;
    QueryPerformanceFrequency(&f);
    QueryPerformanceCounter(&t0);
    src = (char *)malloc(n_pre + n_src + n_post);
    if (!src)
        return -1;
    memcpy(src, g_smaa_pre, n_pre);
    memcpy(src + n_pre, g_smaa_hlsl, n_src);
    memcpy(src + n_pre + n_src, g_smaa_post, n_post);
    hr = make_vs(src, n_pre + n_src + n_post, "twoc_smaa", "edge_vs", &g_aa.edge_vs);
    if (SUCCEEDED(hr))
        hr = make_ps(src, n_pre + n_src + n_post, "twoc_smaa", "edge_ps", &g_aa.edge_ps);
    if (SUCCEEDED(hr))
        hr = make_vs(src, n_pre + n_src + n_post, "twoc_smaa", "weight_vs", &g_aa.weight_vs);
    if (SUCCEEDED(hr))
        hr = make_ps(src, n_pre + n_src + n_post, "twoc_smaa", "weight_ps", &g_aa.weight_ps);
    if (SUCCEEDED(hr))
        hr = make_vs(src, n_pre + n_src + n_post, "twoc_smaa", "blend_vs", &g_aa.blend_vs);
    if (SUCCEEDED(hr))
        hr = make_ps(src, n_pre + n_src + n_post, "twoc_smaa", "blend_ps", &g_aa.blend_ps);
    free(src);
    if (SUCCEEDED(hr))
        hr = make_lut(AREATEX_WIDTH, AREATEX_HEIGHT, DXGI_FORMAT_R8G8_UNORM, areaTexBytes, AREATEX_PITCH, &g_aa.area,
                      &g_aa.area_srv);
    if (SUCCEEDED(hr))
        hr = make_lut(SEARCHTEX_WIDTH, SEARCHTEX_HEIGHT, DXGI_FORMAT_R8_UNORM, searchTexBytes, SEARCHTEX_PITCH,
                      &g_aa.search, &g_aa.search_srv);
    QueryPerformanceCounter(&t1);
    if (FAILED(hr)) {
        fprintf(stderr, "[AA] SMAA not available (0x%08lX): the frame is shown as it is\n", (unsigned long)hr);
        return -1;
    }
    fprintf(stderr, "[AA] SMAA's shaders compiled in %.0f ms\n", (double)(t1.QuadPart - t0.QuadPart) * 1000.0 / f.QuadPart);
    g_aa.smaa = 1;
    return 0;
}

static void size_release(void)
{
    RELEASE(ID3D11ShaderResourceView, g_aa.in_srv);
    RELEASE(ID3D11ShaderResourceView, g_aa.in_srgb);
    RELEASE(ID3D11ShaderResourceView, g_aa.edges_srv);
    RELEASE(ID3D11ShaderResourceView, g_aa.blend_srv);
    RELEASE(ID3D11RenderTargetView, g_aa.out_rtv);
    RELEASE(ID3D11RenderTargetView, g_aa.edges_rtv);
    RELEASE(ID3D11RenderTargetView, g_aa.blend_rtv);
    RELEASE(ID3D11Texture2D, g_aa.in);
    RELEASE(ID3D11Texture2D, g_aa.out);
    RELEASE(ID3D11Texture2D, g_aa.edges);
    RELEASE(ID3D11Texture2D, g_aa.blend);
    g_aa.w = g_aa.h = 0;
}

static HRESULT make_target(unsigned w, unsigned h, DXGI_FORMAT fmt, ID3D11Texture2D **tex,
                           ID3D11RenderTargetView **rtv, ID3D11ShaderResourceView **srv)
{
    ID3D11Device *d = d3d8_GetD3D11Device();
    D3D11_TEXTURE2D_DESC td;
    HRESULT hr;

    memset(&td, 0, sizeof(td));
    td.Width = w;
    td.Height = h;
    td.MipLevels = 1;
    td.ArraySize = 1;
    td.Format = fmt;
    td.SampleDesc.Count = 1;
    td.Usage = D3D11_USAGE_DEFAULT;
    td.BindFlags = D3D11_BIND_RENDER_TARGET | D3D11_BIND_SHADER_RESOURCE;
    hr = ID3D11Device_CreateTexture2D(d, &td, NULL, tex);
    if (SUCCEEDED(hr) && rtv)
        hr = ID3D11Device_CreateRenderTargetView(d, (ID3D11Resource *)*tex, NULL, rtv);
    if (SUCCEEDED(hr) && srv)
        hr = ID3D11Device_CreateShaderResourceView(d, (ID3D11Resource *)*tex, NULL, srv);
    return hr;
}

/* The textures at the frame's size: the frame's copy (typeless, so it can be
 * read as stored and through an sRGB view), the output, and SMAA's edges and
 * weights. */
static int size_fit(unsigned w, unsigned h)
{
    ID3D11Device *d = d3d8_GetD3D11Device();
    D3D11_TEXTURE2D_DESC td;
    D3D11_SHADER_RESOURCE_VIEW_DESC vd;
    HRESULT hr;

    if (g_aa.w == w && g_aa.h == h && g_aa.in)
        return 0;
    size_release();
    memset(&td, 0, sizeof(td));
    td.Width = w;
    td.Height = h;
    td.MipLevels = 1;
    td.ArraySize = 1;
    td.Format = DXGI_FORMAT_R8G8B8A8_TYPELESS;
    td.SampleDesc.Count = 1;
    td.Usage = D3D11_USAGE_DEFAULT;
    td.BindFlags = D3D11_BIND_SHADER_RESOURCE;
    hr = ID3D11Device_CreateTexture2D(d, &td, NULL, &g_aa.in);
    memset(&vd, 0, sizeof(vd));
    vd.ViewDimension = D3D11_SRV_DIMENSION_TEXTURE2D;
    vd.Texture2D.MipLevels = 1;
    vd.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
    if (SUCCEEDED(hr))
        hr = ID3D11Device_CreateShaderResourceView(d, (ID3D11Resource *)g_aa.in, &vd, &g_aa.in_srv);
    vd.Format = DXGI_FORMAT_R8G8B8A8_UNORM_SRGB;
    if (SUCCEEDED(hr))
        hr = ID3D11Device_CreateShaderResourceView(d, (ID3D11Resource *)g_aa.in, &vd, &g_aa.in_srgb);
    if (SUCCEEDED(hr))
        hr = make_target(w, h, DXGI_FORMAT_R8G8B8A8_UNORM, &g_aa.out, &g_aa.out_rtv, NULL);
    if (SUCCEEDED(hr))
        hr = make_target(w, h, DXGI_FORMAT_R8G8_UNORM, &g_aa.edges, &g_aa.edges_rtv, &g_aa.edges_srv);
    if (SUCCEEDED(hr))
        hr = make_target(w, h, DXGI_FORMAT_R8G8B8A8_UNORM, &g_aa.blend, &g_aa.blend_rtv, &g_aa.blend_srv);
    if (FAILED(hr)) {
        size_release();
        fprintf(stderr, "[AA] no textures for a %ux%u frame (0x%08lX)\n", w, h, (unsigned long)hr);
        return -1;
    }
    g_aa.w = w;
    g_aa.h = h;
    return 0;
}

/* ── Passes ────────────────────────────────────────────────── */

static void pass(ID3D11DeviceContext *ctx, ID3D11RenderTargetView *rtv, ID3D11VertexShader *vs,
                 ID3D11PixelShader *ps, ID3D11ShaderResourceView *const *srv)
{
    static ID3D11ShaderResourceView *const none[AA_SRVS];

    ID3D11DeviceContext_PSSetShaderResources(ctx, 0, AA_SRVS, none);   /* last pass's target may be read now */
    ID3D11DeviceContext_OMSetRenderTargets(ctx, 1, &rtv, NULL);
    ID3D11DeviceContext_PSSetShaderResources(ctx, 0, AA_SRVS, srv);
    ID3D11DeviceContext_VSSetShader(ctx, vs, NULL, 0);
    ID3D11DeviceContext_PSSetShader(ctx, ps, NULL, 0);
    ID3D11DeviceContext_Draw(ctx, 3, 0);
}

int aa_post(int mode, ID3D11Texture2D *src, ID3D11Texture2D **out)
{
    ID3D11DeviceContext *ctx = d3d8_GetD3D11Context();
    static const FLOAT zero[4] = { 0, 0, 0, 0 };
    static ID3D11ShaderResourceView *const none[AA_SRVS];
    D3D11_TEXTURE2D_DESC sd;
    float metrics[4];
    saved_t old;

    *out = NULL;
    ID3D11Texture2D_GetDesc(src, &sd);
    if (sd.Format != DXGI_FORMAT_R8G8B8A8_UNORM || sd.SampleDesc.Count != 1 || fx_init() != 0 ||
        (mode == TWOC_AA_SMAA && smaa_init() != 0) || size_fit(sd.Width, sd.Height) != 0)
        return -1;
    ID3D11DeviceContext_CopyResource(ctx, (ID3D11Resource *)g_aa.in, (ID3D11Resource *)src);
    metrics[0] = 1.0f / (float)sd.Width;
    metrics[1] = 1.0f / (float)sd.Height;
    metrics[2] = (float)sd.Width;
    metrics[3] = (float)sd.Height;
    ID3D11DeviceContext_UpdateSubresource(ctx, (ID3D11Resource *)g_aa.cb, 0, NULL, metrics, 0, 0);

    state_save(ctx, &old);
    state_common(ctx, sd.Width, sd.Height);
    ID3D11DeviceContext_VSSetConstantBuffers(ctx, 0, 1, &g_aa.cb);
    ID3D11DeviceContext_PSSetConstantBuffers(ctx, 0, 1, &g_aa.cb);
    if (mode == TWOC_AA_SMAA) {
        ID3D11ShaderResourceView *edge[AA_SRVS] = { g_aa.in_srv };
        ID3D11ShaderResourceView *weight[AA_SRVS] = { NULL, g_aa.edges_srv, g_aa.area_srv, g_aa.search_srv };
        ID3D11ShaderResourceView *blend[AA_SRVS] = { g_aa.in_srv, NULL, NULL, NULL, g_aa.blend_srv, g_aa.in_srgb };
        ID3D11DeviceContext_ClearRenderTargetView(ctx, g_aa.edges_rtv, zero);
        ID3D11DeviceContext_ClearRenderTargetView(ctx, g_aa.blend_rtv, zero);
        pass(ctx, g_aa.edges_rtv, g_aa.edge_vs, g_aa.edge_ps, edge);
        pass(ctx, g_aa.blend_rtv, g_aa.weight_vs, g_aa.weight_ps, weight);
        pass(ctx, g_aa.out_rtv, g_aa.blend_vs, g_aa.blend_ps, blend);
    } else {
        ID3D11ShaderResourceView *fx[AA_SRVS] = { g_aa.in_srv };
        pass(ctx, g_aa.out_rtv, g_aa.vs, g_aa.fxaa_ps, fx);
    }
    ID3D11DeviceContext_PSSetShaderResources(ctx, 0, AA_SRVS, none);
    state_restore(ctx, &old);
    ID3D11Texture2D_AddRef(g_aa.out);
    *out = g_aa.out;
    return 0;
}

int aa_copy(ID3D11RenderTargetView *dst, ID3D11ShaderResourceView *src, unsigned w, unsigned h)
{
    ID3D11DeviceContext *ctx = d3d8_GetD3D11Context();
    ID3D11ShaderResourceView *srv[AA_SRVS] = { src };
    static ID3D11ShaderResourceView *const none[AA_SRVS];
    saved_t old;

    if (fx_init() != 0)
        return -1;
    state_save(ctx, &old);
    state_common(ctx, w, h);
    pass(ctx, dst, g_aa.vs, g_aa.copy_ps, srv);
    ID3D11DeviceContext_PSSetShaderResources(ctx, 0, AA_SRVS, none);
    state_restore(ctx, &old);
    return 0;
}
