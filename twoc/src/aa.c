    "#line 1 \"SMAA.hlsl\"\n";

/* After it: the three passes' entry points. */
static const char g_smaa_post[] =
    "\n#line 1 \"twoc_smaa\"\n"
    "Texture2D colorTex : register(t0);\n"      /* the frame, as stored */
    "Texture2D edgesTex : register(t1);\n"
    "Texture2D areaTex : register(t2);\n"
    "Texture2D searchTex : register(t3);\n"
    "Texture2D blendTex : register(t4);\n"
    "Texture2D colorTexLinear : register(t5);\n"    /* the frame through an sRGB view */
    "float2 tri_uv(uint id) { return float2((id << 1) & 2, id & 2); }\n"
    "float4 tri_pos(float2 uv) { return float4(uv * float2(2, -2) + float2(-1, 1), 0, 1); }\n"
    "struct VE { float4 p : SV_Position; float2 uv : TEXCOORD0; float4 o0 : TEXCOORD1; float4 o1 : TEXCOORD2;"
    " float4 o2 : TEXCOORD3; };\n"
    "VE edge_vs(uint id : SV_VertexID)\n"
    "{\n"
    "    VE o;\n"
    "    float4 off[3];\n"
    "    o.uv = tri_uv(id);\n"
    "    o.p = tri_pos(o.uv);\n"
    "    SMAAEdgeDetectionVS(o.uv, off);\n"
    "    o.o0 = off[0]; o.o1 = off[1]; o.o2 = off[2];\n"
    "    return o;\n"
    "}\n"
    "float4 edge_ps(VE i) : SV_Target\n"
    "{\n"
    "    float4 off[3] = { i.o0, i.o1, i.o2 };\n"
    "    return float4(SMAALumaEdgeDetectionPS(i.uv, off, colorTex), 0, 0);\n"
    "}\n"
    "struct VB { float4 p : SV_Position; float2 uv : TEXCOORD0; float2 pix : TEXCOORD1; float4 o0 : TEXCOORD2;"
    " float4 o1 : TEXCOORD3; float4 o2 : TEXCOORD4; };\n"
    "VB weight_vs(uint id : SV_VertexID)\n"
    "{\n"
    "    VB o;\n"
    "    float4 off[3];\n"
    "    o.uv = tri_uv(id);\n"
    "    o.p = tri_pos(o.uv);\n"
    "    SMAABlendingWeightCalculationVS(o.uv, o.pix, off);\n"
    "    o.o0 = off[0]; o.o1 = off[1]; o.o2 = off[2];\n"
    "    return o;\n"
    "}\n"
    "float4 weight_ps(VB i) : SV_Target\n"
    "{\n"
    "    float4 off[3] = { i.o0, i.o1, i.o2 };\n"
    "    return SMAABlendingWeightCalculationPS(i.uv, i.pix, off, edgesTex, areaTex, searchTex, float4(0, 0, 0, 0));\n"
    "}\n"
    "struct VN { float4 p : SV_Position; float2 uv : TEXCOORD0; float4 o : TEXCOORD1; };\n"
    "VN blend_vs(uint id : SV_VertexID)\n"
    "{\n"
    "    VN o;\n"
    "    o.uv = tri_uv(id);\n"
    "    o.p = tri_pos(o.uv);\n"
    "    SMAANeighborhoodBlendingVS(o.uv, o.o);\n"
    "    return o;\n"
    "}\n"
    "float3 srgb_encode(float3 c) { return c <= 0.0031308 ? c * 12.92 : 1.055 * pow(abs(c), 1.0 / 2.4) - 0.055; }\n"
    "float4 blend_ps(VN i) : SV_Target\n"
    "{\n"
    "    float4 a;\n"     /* SMAANeighborhoodBlendingPS's own test: no weight, the pixel as it is (no sRGB round trip) */
    "    a.x = blendTex.SampleLevel(LinearSampler, i.o.xy, 0).a;\n"
    "    a.y = blendTex.SampleLevel(LinearSampler, i.o.zw, 0).g;\n"
    "    a.wz = blendTex.SampleLevel(LinearSampler, i.uv, 0).xz;\n"
    "    if (dot(a, float4(1.0, 1.0, 1.0, 1.0)) < 1e-5)\n"
    "        return colorTex.SampleLevel(PointSampler, i.uv, 0);\n"
    "    float4 c = SMAANeighborhoodBlendingPS(i.uv, i.o, colorTexLinear, blendTex);\n"
    "    return float4(srgb_encode(saturate(c.rgb)), c.a);\n"
    "}\n";

