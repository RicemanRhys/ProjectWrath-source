/**
 * Anti-aliasing on the host (step 58, notes 18.61). See aa.h.
 *
 * FXAA: one pass, written here after Timothy Lottes' FXAA 3.11 PC "quality"
 * path (preset 39's twelve search steps, sub-pixel 0.75, edge threshold
 * 0.166, minimum 0.0833), with luma computed from the colour (the game's
 * alpha isn't luma).
 *
 * SMAA: Jimenez et al.'s SMAA 1x at its HIGH preset, from the reference
 * shader (third_party/smaa: SMAA.hlsl and its precomputed area and search
 * textures, unchanged). Three passes: luma edges into an R8G8 target, the
 * blending weights into an R8G8B8A8 one, then the neighbourhood blend into
 * the output. The blend reads the frame through an sRGB view and writes it
 * encoded back, as SMAA asks, and a pixel with no blending weight is passed
 * through as stored (the round trip moved some by one level); edge
 * detection reads the frame as stored (gamma).
 * Without SMAA's stencil early-out every pixel runs the weight pass, which
 * returns 0 where there is no edge. SMAA.hlsl is compiled the first time
 * SMAA is used (a few hundred milliseconds, once).
 *
 * Both run on the whole finished frame, so the game's 2D (HUD, text, menus)
 * is smoothed with the 3D: text is a little softer. The settings overlay is
 * drawn after, untouched.
 *
 * aa_copy draws a texture into a render target pixel for pixel (Load, no
 * filtering); with a multisampled target every sample of a pixel gets that
 * pixel. d3d_host.c fills a new or stale multisampled surface with it.
 */

